const isLeader = true;

//Default conditional case for true or false

if (isLeader === true){
    console.log('Stand up');
}
else{
    console.log('Sit Down');

}
//Shortcut form condition for TRUE case
if(isLeader){
    console.log("Stand up");
}
else{
    console.log('Sit Down');

}

//Shortcut form condition for false case

if(!isLeader){
    console.log("Stand up");
}
else{
    console.log('Sit Down');

}
